function localizedCurrencyFormatter(locale: Locale, currency: string) {
  const languageTag = locale === "es-419" ? "es-419" : locale === "pt-BR" ? "pt-BR" : "en-US";
  return new Intl.NumberFormat(languageTag, {
    style: "currency",
    currency: currency || "USD",
    maximumFractionDigits: 0,
  });
}

function localizedPricingBasis(value: string | null, locale: Locale) {
  if (!value) return null;
  const label = PRICING_BASIS_LABELS[value.trim().toLowerCase()] ?? value;
  return marketplaceText(locale, label);
}

export function formatLocalizedProfessionalPrice(
  professional: Pick<ProfessionalProfileRecord, "priceFrom" | "priceTo" | "pricingBasis" | "pricingCurrency" | "contactForPricing">,
  locale: Locale,
) {
  if (professional.contactForPricing) return marketplaceText(locale, "Contact for pricing");
  if (professional.priceFrom == null) return null;

  const formatter = localizedCurrencyFormatter(locale, professional.pricingCurrency);
  const basis = localizedPricingBasis(professional.pricingBasis, locale);
  const suffix = basis ? ` · ${basis}` : "";

  if (professional.priceTo != null && professional.priceTo > professional.priceFrom) {
    return `${formatter.format(professional.priceFrom)}-${formatter.format(professional.priceTo)}${suffix}`;
  }

  return `${marketplaceText(locale, "From")} ${formatter.format(professional.priceFrom)}${suffix}`;
}

export function formatLocalizedServicePrice(
  service: Pick<ProfessionalServiceRecord, "price" | "priceTo" | "pricingBasis" | "contactForPricing" | "currencyCode">,
  locale: Locale,
) {
  if (service.contactForPricing) return marketplaceText(locale, "Contact for pricing");
  if (service.price == null) return null;

  const formatter = localizedCurrencyFormatter(locale, service.currencyCode);
  const basis = localizedPricingBasis(service.pricingBasis, locale);
  const suffix = basis ? ` · ${basis}` : "";

  if (service.priceTo != null && service.priceTo > service.price) {
    return `${formatter.format(service.price)}-${formatter.format(service.priceTo)}${suffix}`;
  }

  return `${formatter.format(service.price)}${suffix}`;
}

